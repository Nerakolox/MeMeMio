/**
 * 图像管线的调优参数。
 *
 * ## 哪些留在这里，哪些已经搬走
 *
 * **判据（SPEC §9.26）：这个参数改变的是**产出**，还是**吞吐**？**
 *
 * - **改产出的留在这里。** `MAX_FRAMES` / `AI_LONG_EDGE` / `COLLAGE_FRAMES` 决定模型
 *   **看到**什么；两个 Hamming 阈值决定什么算重复、也就是用户要在待确认队列里处理多少条。
 *   这一类换一个部署就该是同一份，**因部署而异才是真正的问题**——所以「是常量、不是
 *   环境变量、部署方没有理由调它们」这句话对它们仍然成立（§9.26 原文针对的正是它们）。
 * - **改吞吐的已经搬到 [SPEC §5.6](../../../spec/05-data-models.md) 的 `runtime_config`
 *   单行表**，由 `admin` 在设置页改、**改完不用重启**：打标并发、每用户在途、导入管线
 *   并发、ffmpeg 上限。它们是机器规格相关的数，一台 2 核小机器和一台 16 核机器需要
 *   不同的值，写成常量等于「改一次要改代码 + 重新部署」。
 *
 * ⚠️ **超时留在这里**（`FFMPEG_TIMEOUT_MS` / `FFPROBE_TIMEOUT_MS`）：它们与
 *    `STALE_RUNNING_MS` 有硬关系（回收判据必须明显大于任务超时），两个能独立调节的数
 *    迟早有人把它们调反，而表现是**同一张图付两次钱**（§9.26「本次没做」）。
 */

/**
 * 单次请求最多送 AI 的帧数。
 *
 * 上限只为给成本和请求大小封顶，不是「一般都发全帧」。实测 989 张真实库里
 * 去重后状态数中位数 9、均值 15.3、最大 81，**只有 55% 的动图 ≤10 帧**，
 * 所以采样是常态。取 4 会有 72% 的动图被裁。见 agents/rules/image-pipeline.md §3。
 */
export const MAX_FRAMES = 10

/**
 * 拼图兜底路径固定用 4 帧（且是 2×2）。
 *
 * **和 MAX_FRAMES 不同是有意的**：拼图受限于分辨率而不是数量，3×3 只会让小字更糊。
 * 不要「顺手统一」。见 agents/rules/image-pipeline.md §3。
 */
export const COLLAGE_FRAMES = 4

/** 送 AI 的静图长边。只缩不放——放大不会凭空生出信息，只会让模型把插值糊出来的笔画猜成文字。 */
export const AI_LONG_EDGE = 512

/** 缩略图长边。列表页一屏几十张，直接加载原图会把流量打爆。 */
export const THUMB_LONG_EDGE = 400

/**
 * ffmpeg 子进程超时。**必须有**：一个损坏的文件能让 ffmpeg 挂住不退出，
 * 几个这样的就能把机器打满，而表现只是「导入进度条不动」。见 image-pipeline.md §8。
 */
export const FFMPEG_TIMEOUT_MS = 20_000

/**
 * ffmpeg 并发上限的**默认值**。超时解决单个卡死，并发上限解决它们一起卡死。
 *
 * 每个 ffmpeg 进程都可能吃掉几百 MB 内存，不设上限的话一批损坏文件能把机器打满。
 *
 * ⚠️ **它不再是运行时用的值，只是一处默认值**（SPEC §5.6）：实际上限来自
 *    `runtime_config`，由 `setFfmpegConcurrency`（`probe.ts`）在运行期改。这个常量
 *    留在这里的理由与打标那两个一样——「没配过」要有行为，且「等于默认值就落成 `NULL`」
 *    需要一处比对对象。**默认值只有这份**，`services/runtime-config.ts` import 的是它。
 */
export const FFMPEG_CONCURRENCY = 2

/** ffprobe 只是读容器头，比抽帧轻得多，超时可以更短。 */
export const FFPROBE_TIMEOUT_MS = 8_000

/**
 * 帧间去重的 Hamming 阈值（**不是**入库去重那个阈值）。
 *
 * 作用对象不同：这里比的是同一个文件的相邻帧（长静止段），入库去重比的是跨文件的整图。
 * 两者**不要复用同一个阈值，也不要共用同一个函数名**。见 image-pipeline.md §3 的警告框。
 */
export const FRAME_DEDUP_DISTANCE = 4

/** 单个文件大小上限。超出报 FILE_TOO_LARGE（SPEC §2.3）。 */
export const MAX_FILE_BYTES = 20n * 1024n * 1024n

/**
 * 送进 sharp 的图片**像素数**上限。超出报 FILE_TOO_LARGE（sharp 报
 * `Input image exceeds pixel limit`，`asImageError` 认这句话）。
 *
 * **为什么不能只靠 `MAX_FILE_BYTES`：** 20MB 是**压缩后**的字节数，PNG/WebP 的压缩比
 * 可以到几百倍，一个 20MB 的纯色或噪声图能解出上亿像素。**全解码内存 ≈ 像素 × 4 字节**
 * （RGBA），所以上限要单独按像素数设，字节数管不了它。
 *
 * 取 50 MP 的依据：**单次解码峰值约 200 MB**，是「够用」和「不炸」之间的位置——
 *
 * - 够用：覆盖手机直出的最大一档（48MP），截图、表情包这类内容远在这之下。
 * - 不炸：sharp 默认的 `limitInputPixels` 是 16383² ≈ 2.68 亿像素，全解码约 1 GB。
 *   一个进程同时解两张就足以把 2 核小机器打到 OOM，而用户看到的只是「导入卡住」。
 *
 * ⚠️ **它是单次解码的量，不是进程峰值**：同时解几张由 `runtime_config.importConcurrency`
 *    决定（SPEC §5.6），管理员把它调大时峰值跟着成倍涨。调大这个常量之前先看那个数。
 *
 * 超过的图按 FILE_TOO_LARGE 拒掉、失败原因具体到文件，而不是让 sharp 去解它。
 */
export const MAX_INPUT_PIXELS = 50_000_000

/**
 * 入库近似重复的 Hamming 阈值（**不是**帧间去重那个，见 FRAME_DEDUP_DISTANCE）。
 *
 * 64 位哈希取 8 相当于 ~12.5% 的位差异。**这是保守值，理由是不对称的**：
 * 判成近似重复只是让用户多看一眼（一次点击），漏判会让库里多一份重复——
 * 前者是麻烦，后者是库质量下降且很难事后清理。所以宁可多报。
 *
 * ⚠️ **但这个阈值不是纯调优参数，它决定了用户在待确认队列里要处理多少条。**
 * 调高会明显增加用户的操作量，调低会让重复漏进来。正式取值要靠评测集实测
 * （SPEC §9.16 待验证项），现在这个数字只是有依据的起点，不要当作已校准。
 *
 * 判断权始终在**人**：pHash 会误判——同一模板换了字的两张图距离可能很近，
 * 但它们是两张不同的图。所以这里只攒队列，不做任何自动处理。
 */
export const NEAR_DUP_DISTANCE = 8
